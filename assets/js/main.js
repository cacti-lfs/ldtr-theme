// ── "Voir plus" toggle pour expérience et formations ─────────
document.querySelectorAll('.js-voir-plus').forEach(btn => {
  const targetId  = btn.dataset.target;
  const labelMore = btn.textContent.trim();
  const labelLess = btn.dataset.labelLess || 'Voir moins';

  btn.addEventListener('click', () => {
    const target     = document.getElementById(targetId);
    const hidden     = target.querySelectorAll('.timeline__item--hidden');
    const isExpanded = btn.getAttribute('aria-expanded') === 'true';

    hidden.forEach(item => item.classList.toggle('is-visible', !isExpanded));
    btn.setAttribute('aria-expanded', String(!isExpanded));
    btn.textContent = isExpanded ? labelMore : labelLess;
  });
});
